void _memcpy(void *dst, void *src, unsigned long size)
{
    char *d = (char *)dst;
    char *s = (char *)src;

    while (size > 0)
    {
        size--;
        *d++ = *s++;
    }
}

void fastmemcpy(void *dst, void *src, unsigned long size)
{
    long *d = (long *)dst;
    long *s = (long *)src;

    if ((long)s & 3)
    {
        _memcpy(d, s, size);
        return;
    }
    if ((long)d & 3)
    {
        _memcpy(d, s, size);
        return;
    }
    if (size & 3)
    {
        _memcpy(d, s, size);
        return;
    }

    size >>= 2;
    while (size > 0)
    {
        size--;
        *d++ = *s++;
    }
}

void _memset(void *dst, char value, unsigned long size)
{
    char *d = (char *)dst;

    while (size > 0)
    {
        size--;
        *d++ = value;
    }
}

void clearbufbyte(void *dst, char value, unsigned int size)
{
    char val = value;
    long *d = (long *)dst;

    if ((long)d & 3)
    {
        _memset(d, val, size);
        return;
    }
    if (size & 3)
    {
        _memset(d, val, size);
        return;
    }

    size >>= 2;
    while (size > 0)
    {
        size--;
        *d++ = val | (val << 8) | (val << 16) | val << 24;
    }
}

