float anglemod(float a)
{
    while (a < 0.0f)
        a += 360.0f;
    while (a >= 360.0f)
        a -= 360.0f;
    return a;
}

float getangledelta(float a1, float a2)
{
    if (a1 <= a2)
    {
        a2 -= a1;
        if (a2 <= 180.0f)
            return a2;
        else
            return a2 - 360.0f;
    }
    else
    {
        a1 -= a2;
        if (a1 <= 180.0f)
            return -a1;
        else
            return -(a1 - 360.0f);
    }
}

float getanglef2(float x1, float y1, float x2, float y2)
{
    return 270.0f - (getanglef(y2 - y1, x2 - x1) * 57.29577637f);
}

